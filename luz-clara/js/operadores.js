//operadores.js - Aritméticos y de asignación
const precio = 45000; //Retrato individual
console.log(precio + 5000); //suma = 50000
console.log(precio - 5000); //resta = 40000
console.log(precio * 2); //multiplica = 90000
console.log(precio / 2); //divide = 22500
console.log(7 % 2); //residuo de 7 / 2 = 1
let total = 1000; //variable empieza en cero
total += precio; //igual que total = total + precio
console.log(total); //46000
